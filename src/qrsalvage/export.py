"""Exporting a recovered code, and the evidence that it is right.

The important format here is not a raster one. Whether a printed QR code can be read is decided
by the physical size of a module, not by the pixel count of the file it came from -- a lesson
this project learned from the bulb that started it, whose modules were about 1.4 mm across at
the lowest error correction level. So SVG and PDF carry a real millimetre size, and the raster
export exists for sharing rather than for printing.

Nothing here needs a dependency. A QR code is a page of black rectangles, and writing those
into a PDF directly is a few dozen lines against a library that would have to be installed,
pinned and kept current.
"""

from __future__ import annotations

import base64
import html
import json
from dataclasses import dataclass

import numpy as np

MM_PER_INCH = 25.4
POINTS_PER_INCH = 72.0


@dataclass(frozen=True)
class Layout:
    """How a matrix is placed on a surface."""

    modules: int
    quiet: int = 4
    size_mm: float = 40.0

    @property
    def total_modules(self) -> int:
        return self.modules + 2 * self.quiet

    @property
    def module_mm(self) -> float:
        return self.size_mm / self.total_modules


def _runs(row: np.ndarray):
    """Yield (start, length) of each run of dark modules in a row.

    Merging horizontal runs into single rectangles is not premature tidiness: a version 10 code
    is over three thousand modules, and one rectangle each makes a file several times larger
    than it needs to be for no gain in fidelity.
    """
    start = None
    for index, dark in enumerate(row):
        if dark and start is None:
            start = index
        elif not dark and start is not None:
            yield start, index - start
            start = None
    if start is not None:
        yield start, len(row) - start


def to_svg(matrix: np.ndarray, size_mm: float = 40.0, quiet: int = 4) -> str:
    """Vector export at a real physical size."""
    layout = Layout(modules=int(matrix.shape[0]), quiet=quiet, size_mm=size_mm)
    unit = layout.module_mm

    rectangles = []
    for r, row in enumerate(matrix):
        for start, length in _runs(row):
            x = (start + quiet) * unit
            y = (r + quiet) * unit
            rectangles.append(
                f'<rect x="{x:.4f}" y="{y:.4f}" width="{length * unit:.4f}" height="{unit:.4f}"/>'
            )

    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size_mm}mm" height="{size_mm}mm" '
        f'viewBox="0 0 {size_mm} {size_mm}" shape-rendering="crispEdges">'
        f'<rect width="{size_mm}" height="{size_mm}" fill="#fff"/>'
        f'<g fill="#000">{"".join(rectangles)}</g>'
        "</svg>\n"
    )


def to_pdf(matrix: np.ndarray, size_mm: float = 40.0, quiet: int = 4) -> bytes:
    """A one-page PDF whose page is exactly `size_mm` square.

    Hand-written rather than generated by a library. The document is a catalogue, a page tree,
    one page and one content stream of filled rectangles; the only thing that needs care is the
    cross-reference table, whose byte offsets have to match, and that is what the test checks.
    """
    layout = Layout(modules=int(matrix.shape[0]), quiet=quiet, size_mm=size_mm)
    side = size_mm / MM_PER_INCH * POINTS_PER_INCH
    unit = layout.module_mm / MM_PER_INCH * POINTS_PER_INCH

    parts = ["1 1 1 rg", f"0 0 {side:.4f} {side:.4f} re f", "0 0 0 rg"]
    for r, row in enumerate(matrix):
        for start, length in _runs(row):
            x = (start + quiet) * unit
            # PDF counts upward from the bottom; the matrix counts downward from the top.
            y = side - (r + quiet + 1) * unit
            parts.append(f"{x:.4f} {y:.4f} {length * unit:.4f} {unit:.4f} re")
    parts.append("f")
    stream = "\n".join(parts).encode("ascii")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {side:.4f} {side:.4f}] "
        f"/Contents 4 0 R /Resources << >> >>".encode("ascii"),
        b"<< /Length "
        + str(len(stream)).encode("ascii")
        + b" >>\nstream\n"
        + stream
        + b"\nendstream",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode("ascii") + body + b"\nendobj\n"

    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("ascii")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("ascii")
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_at}\n".encode(
        "ascii"
    )
    out += b"%%EOF\n"
    return bytes(out)


def zigbee_fields(text: str) -> dict | None:
    """Split a Zigbee pairing payload into its parts, if that is what this is.

    Opt-in everywhere it is offered. The install code is a pairing secret rather than an
    identifier, and writing it into its own labelled field makes it that much easier to paste
    somewhere it does not belong.
    """
    if not text.startswith("Z:"):
        return None
    fields: dict[str, str] = {}
    for chunk in text.replace("%", "$").split("$"):
        if len(chunk) > 2 and chunk[1] == ":":
            fields[chunk[0]] = chunk[2:]
    if "Z" not in fields:
        return None

    out = {
        "eui64": fields["Z"],
        "eui64_colons": ":".join(fields["Z"][i : i + 2] for i in range(0, len(fields["Z"]), 2)),
    }
    if "I" in fields and len(fields["I"]) >= 36:
        out["install_code"] = fields["I"][:-4]
        out["install_code_crc"] = fields["I"][-4:]
    if "M" in fields:
        out["model"] = fields["M"]
    if "D" in fields:
        out["batch"] = fields["D"]
    out["warning"] = "install_code is a pairing secret, not an identifier. Do not publish it."
    return out


def to_json(result, include_payload: bool = True, include_zigbee: bool = False) -> str:
    """The result and, just as importantly, how much it can be trusted."""
    out: dict = {
        "recovered": result.solved,
        "failure": result.failure,
        "version": result.version,
        "modules": result.modules,
        "inverted": result.inverted,
        "known_cells_wrong": result.wrong_known,
        "known_cells_total": result.known_total,
        "timing_pattern_percent": None if result.timing is None else round(result.timing * 100, 1),
        "uncertain_cells": result.uncertain,
        "decode_attempts": result.candidates_tried,
        "finders_found": len(result.finders),
    }
    if result.repair is not None:
        out["reed_solomon"] = {
            "failure": result.repair.failure,
            "errors_corrected": result.repair.errors_corrected,
            "erasures_used": result.repair.erasures_used,
            "blocks": result.repair.blocks,
        }
    if include_payload and result.text is not None:
        out["payload"] = result.text
        out["payload_length"] = len(result.text)
        if include_zigbee:
            zigbee = zigbee_fields(result.text)
            if zigbee:
                out["zigbee"] = zigbee
    return json.dumps(out, indent=2) + "\n"


def _data_uri(png: bytes) -> str:
    return "data:image/png;base64," + base64.b64encode(png).decode("ascii")


def to_html_report(result, photo_png: bytes, recovered_png: bytes, clean_png: bytes) -> str:
    """A self-contained page showing the input, the result and the evidence between them.

    Someone who has spent a long time on an unreadable code does not only want a string, they
    want to see why they should believe it. The known-cell count and the timing pattern are that
    evidence, and they belong next to the answer rather than in a log.
    """
    rows = [
        ("version", f"{result.version} ({result.modules} modules)" if result.modules else "-"),
        (
            "known cells wrong",
            f"{result.wrong_known} of {result.known_total}"
            if result.wrong_known is not None
            else "-",
        ),
        ("timing pattern", f"{result.timing * 100:.1f} %" if result.timing is not None else "-"),
        ("uncertain cells", "-" if result.uncertain is None else str(result.uncertain)),
        ("decode attempts", str(result.candidates_tried)),
        ("polarity", "inverted" if result.inverted else "normal"),
    ]
    if result.repair is not None:
        rows.append(
            (
                "reed-solomon",
                result.repair.failure
                or f"{result.repair.errors_corrected} errors, "
                f"{result.repair.erasures_used} erasures",
            )
        )

    table = "".join(f"<tr><th>{html.escape(k)}</th><td>{html.escape(v)}</td></tr>" for k, v in rows)
    verdict = (
        f'<p class="ok">Recovered {len(result.text)} characters</p>'
        f"<pre>{html.escape(result.text)}</pre>"
        if result.solved
        else f'<p class="bad">Not recovered — {html.escape(result.failure or "unknown")}</p>'
    )
    panels = [("Input", photo_png), ("Recovered matrix", recovered_png)]
    if result.solved:
        panels.append(("Re-encoded", clean_png))
    images = "".join(
        f'<figure><img src="{_data_uri(png)}" alt="{name}"><figcaption>{name}</figcaption></figure>'
        for name, png in panels
        if png
    )

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>qrsalvage report</title><style>
body{{font:15px/1.6 ui-sans-serif,system-ui,sans-serif;max-width:60rem;margin:2rem auto;
padding:0 1rem;color:#1a1a19;background:#fbfbfa}}
h1{{font-size:1.4rem;margin:0}} .sub{{color:#6b6b66;font-style:italic;margin:.2rem 0 1.5rem}}
figure{{margin:0}} figure img{{max-width:100%;border:1px solid #e0e0dc;border-radius:6px}}
figcaption{{color:#6b6b66;font-size:.85rem;margin-top:.4rem}}
.row{{display:flex;gap:1rem;flex-wrap:wrap}} .row figure{{flex:1 1 14rem}}
table{{border-collapse:collapse;margin:1.5rem 0}}
th,td{{text-align:left;padding:.35rem 1.2rem .35rem 0;border-bottom:1px solid #e0e0dc}}
th{{font-weight:500;color:#6b6b66}} td{{font-variant-numeric:tabular-nums}}
pre{{background:#fff;border:1px solid #e0e0dc;border-radius:6px;padding:.8rem;
white-space:pre-wrap;word-break:break-all}}
.ok{{color:#2f6f4f;font-weight:600}} .bad{{color:#a33a2a;font-weight:600}}
</style></head><body>
<h1>qrsalvage report</h1><p class="sub">recover QR codes from what's left of them</p>
<div class="row">{images}</div>
<table>{table}</table>
{verdict}
</body></html>
"""
